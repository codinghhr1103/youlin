const LANG_KEY = "youlin_lang";

function detectLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === "en" || saved === "zh") return saved;
  } catch (_) {
    /* private mode or missing storage */
  }
  const nav = String(navigator.language || "zh").toLowerCase();
  return nav.startsWith("zh") ? "zh" : "en";
}

let currentLang = detectLang();

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  currentLang = lang === "en" ? "en" : "zh";
  try {
    localStorage.setItem(LANG_KEY, currentLang);
  } catch (_) {
    /* ignore */
  }
  applyDocumentLang();
}

export function applyDocumentLang() {
  document.documentElement.lang = currentLang === "en" ? "en" : "zh-CN";
  document.title = t("meta.title");
}

function lookup(dict, key) {
  return key.split(".").reduce((node, part) => (node == null ? node : node[part]), dict);
}

export function t(key, vars = {}) {
  const text = lookup(STRINGS[currentLang], key) ?? lookup(STRINGS.zh, key) ?? key;
  return String(text).replace(/\{(\w+)\}/g, (_, name) => (vars[name] == null ? `{${name}}` : String(vars[name])));
}

export function localizeError(message) {
  if (!message) return t("errors.requestFailed");
  if (currentLang !== "en") return message;
  return ERRORS_EN[message] || message;
}

