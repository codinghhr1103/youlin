export function localizeStamp(stamp) {
  if (!stamp) return stamp;
  if (currentLang !== "en") return stamp;
  const extra = STAMP_EN[stamp.catalog_no] || {};
  return {
    ...stamp,
    name: extra.name || stamp.name,
    theme: extra.theme || THEME_EN[stamp.theme] || stamp.theme,
    issuer: extra.issuer || ISSUER_EN[stamp.issuer] || stamp.issuer,
    face_value: extra.face_value || stamp.face_value,
    description: extra.description || stamp.description,
    image_credit: extra.image_credit || CREDIT_EN[stamp.image_credit] || stamp.image_credit,
  };
}

